import test from 'node:test';
import assert from 'node:assert/strict';
import { readFile, writeFile, mkdtemp, mkdir, access } from 'node:fs/promises';
import { join } from 'node:path';
import { tmpdir } from 'node:os';
import { execFile } from 'node:child_process';
import { promisify } from 'node:util';
const exec = promisify(execFile);
const runtime = process.env.RUFA_TEST_RUNTIME_ROOT;
test('offline Remotion renders H264/AAC and inspects real encoded frames in a Unicode path', { skip: !runtime, timeout: 180000 }, async () => {
  const project = join(await mkdtemp(join(tmpdir(), 'rufa-remotion-accept-')), '视频验收 空格');
  const runner = join(runtime, 'company-tools/remotion/runner.mjs');
  const run = (...args) => exec(process.execPath, [runner, ...args], { windowsHide: true, timeout: 150000, maxBuffer: 4 * 1024 * 1024 });
  await run('init', project);
  await assert.rejects(run('init', project), /existing files|empty project/i);
  await writeFile(join(project, 'src/Root.tsx'), `import React from 'react';
import {AbsoluteFill, Audio, Composition, staticFile, useCurrentFrame, useVideoConfig, spring} from 'remotion';
const Clip = () => {const frame=useCurrentFrame(); const {fps}=useVideoConfig(); const p=spring({frame,fps});return <AbsoluteFill style={{background:'#102333',alignItems:'center',justifyContent:'center',color:'white',fontFamily:'Arial'}}><div style={{transform:'scale('+p+')',fontSize:28}}>Rufajx-DSH</div><Audio src={staticFile('tone.wav')}/></AbsoluteFill>};
export const Root=()=> <Composition id="Acceptance" component={Clip} width={320} height={180} fps={30} durationInFrames={30}/>;
`);
  const samples = 48000, wave = Buffer.alloc(44 + samples * 2);
  wave.write('RIFF'); wave.writeUInt32LE(wave.length - 8, 4); wave.write('WAVEfmt ', 8); wave.writeUInt32LE(16, 16); wave.writeUInt16LE(1, 20); wave.writeUInt16LE(1, 22); wave.writeUInt32LE(48000, 24); wave.writeUInt32LE(96000, 28); wave.writeUInt16LE(2, 32); wave.writeUInt16LE(16, 34); wave.write('data', 36); wave.writeUInt32LE(samples * 2, 40);
  for (let i = 0; i < samples; i++) wave.writeInt16LE(Math.round(Math.sin(i * Math.PI * 2 * 440 / 48000) * 1000), 44 + i * 2);
  await writeFile(join(project, 'public/tone.wav'), wave);
  const entry = join(project, 'src/index.ts'), video = join(project, '验收.mp4');
  await run('render', entry, 'Acceptance', video);
  const metadata = JSON.parse((await run('probe', video)).stdout);
  assert.equal(metadata.streams.find(s => s.codec_type === 'video').codec_name, 'h264');
  assert.equal(metadata.streams.find(s => s.codec_type === 'audio').codec_name, 'aac');
  assert.ok(Number(metadata.format.duration) >= 1);
  await run('frame', video, join(project, 'encoded.png'), '--time', '0.5');
  await run('still', entry, 'Acceptance', join(project, 'still.png'), '--frame', '15');
  for (const file of ['encoded.png', 'still.png']) assert.equal((await readFile(join(project, file))).subarray(1, 4).toString(), 'PNG');
  await assert.rejects(run('frame', video, join(project, 'encoded.png'), '--time', '0.5'), /already exists/);
  await assert.rejects(access(join(project, 'node_modules')));
  console.log(`Desktop/video acceptance artifacts: ${project}`);
});
